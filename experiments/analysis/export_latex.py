def _date_range(calls: pd.DataFrame) -> str | None:
    if calls.empty or "started_at" not in calls:
        return None
    t = pd.to_datetime(calls["started_at"], utc=True, errors="coerce").dropna()
    if t.empty:
        return None
    a, b = t.min().date(), t.max().date()
    mon = lambda d: d.strftime("%B")
    if a == b:
        return f"{a.day} {mon(a)} {a.year}"
    if (a.year, a.month) == (b.year, b.month):
        return f"{a.day}--{b.day} {mon(a)} {a.year}"
    if a.year == b.year:
        return f"{a.day} {mon(a)}--{b.day} {mon(b)} {a.year}"
    return f"{a.day} {mon(a)} {a.year}--{b.day} {mon(b)} {b.year}"


def values(res: dict, inputs) -> Values:
    V = Values()
    M = inputs.models
    # ---- study-level counts
    e1_models = set()
    for df in (inputs.gen, inputs.repair, inputs.audit):
        if not df.empty:
            e1_models |= set(df["model_key"].unique())
    if e1_models:
        V.add("n-models-e1", str(len(e1_models)))
    if not inputs.steps.empty:
        V.add("n-models-e2", str(inputs.steps["model_key"].nunique()))
    if not inputs.generated.empty:
        g = inputs.generated
        g = g[g["status"] == "ok"] if "status" in g else g
        if len(g):
            V.add("n-models-e3gen", str(g["generator"].nunique()))
    sc = study_calls(inputs.calls)
    if not sc.empty:
        V.add("total-calls", integer(len(sc)))
        V.add("total-cost", usd(float(pd.to_numeric(sc["cost_usd"], errors="coerce").fillna(0).sum())))
        V.add("run-dates", _date_range(sc))
    meta = inputs.meta or {}
    for k_meta, k in (("axe_version", "axe-version"), ("chromium_version", "chromium-version"),
                      ("probe_count", "probe-count"), ("prereg_hash", "prereg-hash")):
        if meta.get(k_meta) not in (None, ""):
            V.add(k, tex_escape(str(meta[k_meta])))
    if inputs.snapshot_date:
        V.add("price-snapshot-date", inputs.snapshot_date)

    # ---- E1
    for m, r in res["gen"]["models"].items():
        V.est(f"sgen-{m}", r["sgen_nudged"])
        V.est(f"sgen-unguided-{m}", r["sgen_unguided"])
        V.est(f"gap-{m}", r["gap"])
        V.est(f"overclaim-{m}", r["overclaim"])
        V.est(f"clean-nudged-{m}", r["clean_nudged"])
        V.add(f"gen-errors-{m}", str(r["n"]["error"]))
        V.add(f"vp100-nudged-{m}", num(r["vp100_nudged"], 1))
        V.add(f"vp100-unguided-{m}", num(r["vp100_unguided"], 1))
        V.add(f"selfassess-unparsed-{m}", str(r["n"]["selfassess_unparsed"]))
    for m, r in res["rep"]["models"].items():
        V.est(f"srep-{m}", r["srep"])
        V.est(f"fullrepair-{m}", r["full_repair"])
        V.est(f"regressions-{m}", r["regressions"])
        V.est(f"preserved-{m}", r["preserved"])
        for p, e in r["by_provenance"].items():
            V.est(f"srep-{p}-{m}", e)
        for op, e in r["per_operator"].items():
            V.est(f"resolve-{op}-{m}", e)
    for op, v in res["rep"].get("pooled_operator", {}).items():
        V.add(f"resolve-{op}", num(v))
    for m, r in res["aud"]["models"].items():
        V.est(f"saudit-{m}", r["saudit"])
        V.est(f"audit-precision-{m}", r["precision"])
        V.est(f"audit-recall-{m}", r["recall"])
        V.est(f"audit-parsefail-{m}", r["parse_fail"])

    # ---- E2
    for m, r in res["dcdi"]["models"].items():
        V.est(f"dcdi-{m}", r["dcdi"])
    for m, r in res["decomp"]["models"].items():
        V.est(f"dcdi-k-{m}", r["tot"])
        V.est(f"dcdi-len-{m}", r["len"])
        V.est(f"dcdi-hist-{m}", r["hist"])
    for m, r in res["beta"].items():
        if r.get("beta") is not None:
            V.add(f"beta-{m}", num(r["beta"], 3))
            V.add(f"beta-{m}-lo", num(r["lo"], 3))
            V.add(f"beta-{m}-hi", num(r["hi"], 3))
            V.add(f"beta-{m}-ci", f"[{num(r['lo'], 3)}, {num(r['hi'], 3)}]")
            V.add(f"beta-{m}-n", integer(r["n"]))
    for m, r in res["press"]["models"].items():
        V.est(f"pressure-{m}", r["pressure"])
        V.est(f"intent-{m}", r["intent_met"])
    for m, r in res["sess"]["models"].items():
        V.est(f"endreg-{m}", r["end_regression"])
        if r["tool_cycles_mean"] is not None:
            V.add(f"toolcycles-{m}", num(r["tool_cycles_mean"], 1))
    if res["sess"].get("mean_tool_cycles") is not None:
        V.add("e2-mean-tool-cycles", num(res["sess"]["mean_tool_cycles"], 1))
    for m, arms in res.get("toolcalls", {}).items():
        rate = arms.get("session", {}).get("rate")
        if rate is not None:
            V.add(f"malformed-rate-{m}", num(rate, 3))
    for m, d in res["drops"].items():
        V.add(f"e2-drops-{m}", str(d["pairs"] - d["kept"]))
        V.add(f"e2-kept-{m}", str(d["kept"]))

    # ---- dimensions, CCS
    for m, d in res["dims"].items():
        for k, e in d.items():
            V.est(f"{k.lower()}-{m}", e)
    for m, s in res["ccs"].items():
        V.est(f"ccs-{m}", s["ccs"])
        if s["partial"] is not None:
            V.add(f"ccs-partial-{m}", num(s["partial"]))
        if s["arith"] is not None:
            V.add(f"ccs-arith-{m}", num(s["arith"]))
    rs = res["rank_stability"]
    if rs["arith"][0] is not None:
        V.add("tau-ccs-arith", num(rs["arith"][0]))
    loo = [t for t, _ in rs["loo"].values() if t is not None]
    if loo:
        V.add("tau-ccs-loo-min", num(min(loo)))
    for pair, (t, n) in rs["dimension_pairs"].items():
        if t is not None:
            V.add(f"tau-{pair}", num(t))
            V.add(f"tau-{pair}-n", str(n))

    # ---- CPDS
    cp = res["cpds"]
    for scen, vals in cp["cpds"].items():
        for m, v in vals.items():
            V.add(f"cpds-{scen}-{m}", num(v))
    for fam, pis in cp["pi"].items():
        tag = "batch" if fam == "rep" else "gen"
        for m, v in pis.items():
            V.add(f"pi-{tag}-{m}", num(v))
    for fam, summ in cp["summary"].items():
        for m, s in summ.items():
            V.add(f"cost-{fam}-{m}", usd(s["c"]))
            if s["l"] is not None:
                V.add(f"lat-{fam}-{m}", num(s["l"], 1))
    for m, a in cp["affordability"].items():
        V.add(f"cost1000-{m}", usd(a["cost_1000_pages"]))
        if a.get("page_tokens") is not None:
            V.add(f"pagetokens-{m}", integer(a["page_tokens"]))
    for scen, s in cp["sensitivity"].items():
        V.add(f"tau-cpds-{scen}-min", num(s["min"]))
        V.add(f"tau-cpds-{scen}-median", num(s["median"]))
    for fam, front in cp["frontier"].items():
        tag = "batch" if fam == "rep" else "gen"
        if front:
            V.add(f"pareto-{tag}", ", ".join(tex_escape(display(M, m)) for m in front))

    # ---- E3
    e3 = res["e3"]
    c = e3.get("e3c", {})
    if c:
        for g, e in c["s4"].items():
            V.est(f"s4-{g}", e)
            V.est(f"theta-{g}", c["theta"][g])
        for j in c["judges"]:
            V.est(f"gamma-{j}", c["gamma"][j])
            V.est(f"delta-{j}", c["delta"][j])
            V.est(f"eta-{j}", c["eta"][j])
            V.est(f"pc-{j}", c["pc"].get(j))
        V.add("pc-naive", num(c["naive"].get("pc")))
        V.add("gamma-naive", num(c["naive"].get("gamma")))
        V.add("kalpha-e3c", num(c.get("kalpha")))
        V.add("e3c-judgments", integer(c["n_judgments"]))
        V.add("e3c-recused", integer(c["n_recused"]))
        V.add("e3c-images", integer(c["n_images"]))
    kn = e3.get("known", {})
    if kn:
        for grp, accs in kn["accuracy"].items():
            for mth, e in accs.items():
                tag = mth.replace("single:", "")
                key = f"acc-known-{tag}" if grp == "all" else f"acc-known-{grp}-{tag}"
                V.est(key, e)
        V.est("h4b-diff", kn.get("h4b"))
        V.add("kalpha-e3b", num(kn.get("kalpha")))
        for j, e in kn.get("pc", {}).items():
            V.est(f"pc-known-{j}", e)
    bp = e3.get("blv_pairs", {})
    for mth, e in (bp.get("accuracy", {}).get("all", {}) if bp else {}).items():
        V.est(f"acc-blvpairs-{mth.replace('single:', '')}", e)
    for ds, tag in (("blv", "blv"), ("cr", "crowd")):
        for mth, v in e3.get("pointwise", {}).get(ds, {}).items():
            if isinstance(v, dict) and "r" in v:
                name = mth.replace("single:", "")
                V.est(f"r-{tag}-{name}", v["r"])
                V.est(f"tau-{tag}-{name}", v["tau"])
    for mth, e in e3.get("pointwise", {}).get("crowd_minus_blv", {}).items():
        V.est(f"r-crowd-minus-blv-{mth.replace('single:', '')}", e)
    lk = e3.get("leakage", {})
    if lk.get("accuracy") is not None:
        V.add("leak-acc", num(lk["accuracy"]))
        V.add("leak-acc-ci", f"[{num(lk['lo'])}, {num(lk['hi'])}]")
        V.add("leak-majority", num(lk["majority"]))
        V.add("leak-n", integer(lk["n"]))

    # ---- hypotheses
    for name, t in res["hyp"]["tests"].items():
        k = name.lower()
        if not t.get("tested"):
            V.add(f"{k}-result", "not tested")
            continue
        V.add(f"{k}-p", num(t["p"], 3))
        V.add(f"{k}-padj", num(t["p_holm"], 3))
        V.add(f"{k}-result", "supported" if t["supported"] else "not supported")
        if isinstance(t.get("stat"), Est):
            V.est(f"{k}-stat", t["stat"])
    h3 = res["hyp"]["tests"].get("H3", {})
    if h3.get("tested"):
        V.add("h3-best-open", tex_escape(display(M, h3["best_open"])))
        V.add("h3-pi", num(h3["pi"]))
    h5 = res["hyp"]["tests"].get("H5", {})
    if h5.get("tested"):
        V.add("h5-count", f"{h5['count_positive']} of {h5['models']}")
    V.add("hyp-family-size", str(res["hyp"]["family_size"]))

    # ---- decision matrix
    for ctx, (first, second) in res["decision"].items():
        V.add(f"dm-{ctx}", tex_escape(display(M, first)) if first != "none" else "none")
        V.add(f"dm-{ctx}-runner", tex_escape(display(M, second)) if second != "none" else "none")
    return V


def write_all(res: dict, inputs, results_dir: pathlib.Path) -> list[pathlib.Path]:
    results_dir = pathlib.Path(results_dir)
    results_dir.mkdir(parents=True, exist_ok=True)
    paths = []
