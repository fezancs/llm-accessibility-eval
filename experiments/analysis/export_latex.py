def ttc_label(s: str) -> str:
    s = (s or "").lower()
    if "adaptive" in s:
        return "adaptive"
    if "thinking only" in s:
        return "always"
    if "modes" in s or "non-thinking" in s:
        return "modes"
    if "effort" in s:
        return "effort"
    if "thinking" in s:
        return "thinking"
    return "--"


def arch_label(s: str) -> str:
    s = (s or "").strip()
    if not s or "undisclosed" in s.lower():
        return "und."
    nums = re.findall(r"(\d+(?:\.\d+)?)\s*([BT])\b", s)
    if "moe" in s.lower() and len(nums) >= 2:
        return f"MoE {nums[0][0]}{nums[0][1]}/{nums[1][0]}{nums[1][1]}"
    if "dense" in s.lower() and nums:
        return f"dense {nums[0][0]}{nums[0][1]}"
    return tex_escape(re.sub(r"\s*\(.*?\)", "", s))


def price_label(v) -> str:
    if v is None:
        return "--"
    return f"{int(v)}" if float(v).is_integer() else f"{v:.2f}"


def models_used(inputs) -> dict[str, set]:
    use: dict[str, set] = {}

    def mark(keys, tag):
        for k in keys:
            use.setdefault(k, set()).add(tag)
    for df in (inputs.gen, inputs.repair, inputs.audit):
        if not df.empty:
            mark(df["model_key"].unique(), "1")
    if not inputs.steps.empty:
        mark(inputs.steps["model_key"].unique(), "2")
    if not inputs.generated.empty:
        g = inputs.generated
        if "status" in g:
            g = g[g["status"] == "ok"]
        mark(g["generator"].unique(), "G")
    for df in (inputs.pointwise, inputs.known_pairs, inputs.gen_pairs, inputs.blv_pairs):
        if not df.empty:
            mark(df["judge"].unique(), "J")
    return use


def table_models(inputs) -> str:
    use = models_used(inputs)
    rows, notes = [], set()
    for key, m in inputs.models.items():
        if key not in use:
            continue
        name = tex_escape(m.get("display", key))
        if m.get("tier") == "optional":
            name += "$^{\\dagger}$"
            notes.add("dagger")
        price = m.get("price") or {}
        p = f"{price_label(price.get('input'))}/{price_label(price.get('output'))}"
        tiers = ([100_000] if "price_over_100k" in m else []) + \
            ([int(m["price_long_context"]["over_prompt_tokens"])] if m.get("price_long_context") else [])
        if tiers:
            p += "$^{a}$"
            notes.update(("a", t, m.get("display", key)) for t in tiers)
        changes = sorted(str(c.get("from")) for c in m.get("price_changes") or [])
        if changes:                          # introductory price (models.yaml price_changes)
            p += "$^{b}$"
            notes.add(("b", changes[0], m.get("display", key)))
        if "price_offpeak" in m:
            p += "$^{c}$"
            notes.add(("c", (m.get("price_offpeak") or {}).get("input"), price.get("input")))
        tags = [t for t in ("1", "2", "G", "J") if t in use[key]]
        rows.append(" & ".join([name, "\\checkyes" if m.get("access") == "open" else "--",
                                arch_label(m.get("architecture")), "\\checkyes" if m.get("vision") else "--",
                                ttc_label(m.get("test_time_compute")), p, "\\,".join(tags)]) + "\\\\")
    foot = []
    if "dagger" in notes:
        foot.append("$^{\\dagger}$Optional (budget permitting).")
    def grouped(tag: str, label) -> str:
        """'<value> (Model A, Model B); <value> (Model C)' for footnote `tag`, in value order."""
        by: dict = {}
        for n in notes:
            if isinstance(n, tuple) and n[0] == tag:
                by.setdefault(n[1], []).append(tex_escape(n[2]))
        return "; ".join(f"{label(v)} ({', '.join(sorted(ms))})" for v, ms in sorted(by.items()))

    if any(isinstance(n, tuple) and n[0] == "a" for n in notes):
        foot.append("$^{a}$Prompts up to " + grouped("a", lambda t: f"{t // 1000}k tokens") + ".")
    if any(isinstance(n, tuple) and n[0] == "b" for n in notes):
        def until(d: str) -> str:
            x = dt.date.fromisoformat(d) - dt.timedelta(days=1)
            return f"{x.day} {x:%b %Y}"
        foot.append("$^{b}$Introductory price until " + grouped("b", until) + ".")
    for n in notes:
        if isinstance(n, tuple) and n[0] == "c":
            half = n[1] is not None and n[2] and abs(n[1] * 2 - n[2]) < 1e-9
            foot.append("$^{c}$Peak hours; " + ("half price off-peak." if half else "lower price off-peak."))
    foot.append("Open-weight prices are those of the hosting provider used.")
    body = HEADER + "% Models actually run and the prices used (config/models.yaml).\n" + "\n".join(rows) + "\n"
    body += "\\multicolumn{7}{@{}p{0.95\\columnwidth}@{}}{\\tiny " + " ".join(foot) + "}\\\\\n"
    return body


