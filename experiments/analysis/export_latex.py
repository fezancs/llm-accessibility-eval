# ------------------------------------------------------------------ number formatting

def num(x: float | None, d: int = 2) -> str | None:
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return None
    s = f"{x:.{d}f}"
    if s.startswith("-"):
        if float(s) == 0:
            s = s[1:]
        else:
            s = "$-$" + s[1:]
    return s


def usd(x: float | None) -> str | None:
    if x is None or not math.isfinite(x):
        return None
    if x == 0:
        return "\\$0"
    if x < 0.01:
        return f"\\${x:.4f}"
    if x < 1:
        return f"\\${x:.3f}"
    return "\\$" + f"{x:,.2f}".replace(",", "{,}")


def integer(x) -> str | None:
    if x is None:
        return None
    return f"{int(round(x)):,}".replace(",", "{,}")


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", str(s).lower()).strip("-")


def tex_escape(s: str) -> str:
    return (str(s).replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%")
            .replace("$", "\\$").replace("#", "\\#").replace("_", "\\_").replace("{", "\\{").replace("}", "\\}"))


class Values:
    def __init__(self):
        self.v: dict[str, str] = {}

    def add(self, key: str, value: str | None):
        if value is not None:
            self.v[slug(key) if not key.startswith("__") else key] = value

    def est(self, key: str, e: Est | None, d: int = 2, fmt=None):
        if e is None or not e.ok:
            return
        f = fmt or (lambda x: num(x, d))
        self.add(key, f(e.est))
        if e.lo is not None and e.hi is not None:
            self.add(f"{key}-lo", f(e.lo))
            self.add(f"{key}-hi", f(e.hi))
            self.add(f"{key}-ci", f"[{f(e.lo)}, {f(e.hi)}]")
        if e.n:
            self.add(f"{key}-n", integer(e.n))

    def write(self, path: pathlib.Path):
        lines = [HEADER, "% Every \\res{key} the paper uses must be defined here by the analysis.\n"]
        for k in sorted(self.v):
            lines.append(f"\\setres{{{k}}}{{{self.v[k]}}}\n")
        path.write_text("".join(lines), encoding="utf-8")


def cell(e: Est | None, d: int = 2) -> str:
    if e is None or not e.ok:
        return "--"
    return num(e.est, d)


