"""Write paper/results/*.tex from the analysis results (SPEC 11). Never hand-edit the outputs.

values.tex holds \\setres{key}{value} lines. Keys are lowercase and hyphenated; an estimate
`k` comes with `k-lo`, `k-hi`, `k-ci` ("[lo, hi]") and `k-n`. A key is written only when its
data exist, so the paper prints TBD (draft) or stops (final) for anything that did not run.
Table cells for quantities not measured are "--".

Required keys outside results paragraphs (SPEC 11): n-models-e1, n-models-e2, n-models-e3gen,
axe-version, chromium-version, run-dates, total-calls, total-cost, e2-mean-tool-cycles,
probe-count, prereg-hash, dm-*. axe-version, chromium-version, probe-count and prereg-hash
come from runs/meta.json (written by the harness); they are omitted if it is missing.
"""
