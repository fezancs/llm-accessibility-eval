def table_cmbpe(res: dict, inputs) -> str:
    e3 = res["e3"]
    pw = e3.get("pointwise", {})
    kn = e3.get("known", {})
    c = e3.get("e3c", {})
    pc_src = c.get("pc") if c else kn.get("pc", {})

    def r_of(ds, mth):
        e = pw.get(ds, {}).get(mth, {}).get("r") if isinstance(pw.get(ds, {}).get(mth), dict) else None
        return cell(e)

    def acc_of(mth):
        return cell(kn.get("accuracy", {}).get("all", {}).get(mth)) if kn else "--"

    rows = []
    for j in e3.get("judges", []):
        name = tex_escape(display(inputs.models, j)) + " (single)"
        rows.append(" & ".join([name, r_of("blv", f"single:{j}"), r_of("cr", f"single:{j}"), acc_of(f"single:{j}"),
                                cell((pc_src or {}).get(j)), cell(c.get("gamma", {}).get(j) if c else None),
                                cell(c.get("eta", {}).get(j) if c else None)]) + "\\\\")
    rows.append("\\midrule")
    nv = c.get("naive", {}) if c else {}
    rows.append(" & ".join(["Naive panel", r_of("blv", "naive"), r_of("cr", "naive"), acc_of("naive"),
                            num(nv.get("pc")) or "--", num(nv.get("gamma")) or "--", "--"]) + "\\\\")
    rows.append(" & ".join(["CMBPE", r_of("blv", "cmbpe"), r_of("cr", "cmbpe"), acc_of("cmbpe"),
                            "--", "--", "--"]) + "\\\\")
    rows.append(" & ".join(["Length only (baseline)", r_of("blv", "length"), r_of("cr", "length"),
                            "--", "--", "--", "--"]) + "\\\\")
    return HEADER + "% Table IV: judge reliability (E3).\n" + "\n".join(rows) + "\n"


