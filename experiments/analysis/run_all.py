RECORD_FILES = ["runs/e1/scores/gen.jsonl", "runs/e1/scores/repair.jsonl", "runs/e1/scores/audit.jsonl",
                "runs/e2/scores/steps.jsonl", "runs/e3/judgments/pointwise.jsonl",
                "runs/e3/judgments/known_pairs.jsonl", "runs/e3/judgments/gen_pairs.jsonl", "runs/e3/generated.jsonl"]


def compute(inputs, b: int = B_DEFAULT, seed: int = SEED) -> dict:
    res = {"B": b, "seed": seed}
    res["gen"] = metrics.e1_gen(inputs.gen, b, seed)
    res["rep"] = metrics.e1_repair(inputs.repair, b, seed)
    res["aud"] = metrics.e1_audit(inputs.audit, b, seed)
    pairs = dcdi.paired(inputs.steps)
    res["dcdi"] = dcdi.dcdi(pairs, b, seed)
    res["decomp"] = dcdi.decomposition(pairs, b, seed)
    res["beta"] = dcdi.drift_rate(pairs)
    res["drops"] = dcdi.drops(pairs)
    res["curves"] = dcdi.curves(pairs, b, seed)
    res["press"] = metrics.e2_pressure(inputs.steps, b, seed)
    res["sess"] = metrics.e2_sessions(inputs.sessions, b, seed)
    res["toolcalls"] = metrics.e2_tool_calls(inputs.steps)
    res["e3"] = cmbpe_bt.analyse(inputs, b, seed)
    s4 = res["e3"].get("e3c", {}).get("s4", {}) if res["e3"].get("e3c") else {}
    res["cpds"] = cpds.analyse(inputs.gen, inputs.repair, b, seed)
    res["dims"] = ccs.dimensions(res["gen"]["models"], res["rep"]["models"], res["aud"]["models"],
                                 res["dcdi"]["models"], s4, res["press"]["models"], b)
    res["ccs"] = ccs.ccs(res["dims"], b)
    res["rank_stability"] = ccs.rank_stability(res["dims"], res["ccs"])
    e1_models = set(res["gen"]["models"]) | set(res["rep"]["models"]) | set(res["aud"]["models"])
    dm = ccs.decision_matrix(res["dims"], res["ccs"], inputs.models, res["cpds"]["pi"].get("rep", {}),
                             res["cpds"]["cpds"].get("batch", {}), e1_models)
    # Write a rule's outcome only when the experiments it depends on produced data.
    ran = {"e1": bool(e1_models), "e2": bool(res["dcdi"]["models"]), "e3": bool(s4)}
    need = {"enterprise": ran["e1"] and ran["e2"] and ran["e3"], "research": any(ran.values()),
            "public": bool(res["cpds"]["cpds"].get("batch")), "edge": any(ran.values())}
    res["decision"] = {k: v for k, v in dm.items() if need[k]}
    eta = res["e3"].get("e3c", {}).get("eta", {}) if res["e3"].get("e3c") else {}
    h4b = res["e3"].get("known", {}).get("h4b") if res["e3"].get("known") else None
    res["hyp"] = hypotheses.run(res["gen"]["models"], res["dcdi"]["models"], s4,
                                res["cpds"]["pi"].get("rep", {}), eta, h4b, inputs.models, b)
    return res


# ------------------------------------------------------------------ summary.md

def f(e: Est | None, d: int = 3) -> str:
    if e is None or not e.ok:
        return "--" + (f" ({e.note})" if e is not None and e.note else "")
    ci = f" [{e.lo:.{d}f}, {e.hi:.{d}f}]" if e.lo is not None else ""
    return f"{e.est:.{d}f}{ci} (n={e.n})"


def table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def summary(res: dict, inputs, values: dict, figs: list, wrote_paper: bool) -> str:
    M = inputs.models
    nm = lambda m: display(M, m)
    L = ["# Analysis summary", "",
         f"Generated by `analysis/run_all.py` from the logged records; B = {res['B']} bootstrap resamples, "
         f"seed {res['seed']}. 95% percentile CIs. Every number below is computed from logged API outputs; "
         "nothing is imputed. `--` means not measured.", ""]
    L.append("## Inputs\n")
    L.append(table(["file", "records"], [[k, len(df)] for k, df in (
        ("runs/e1/scores/gen.jsonl", inputs.gen), ("runs/e1/scores/repair.jsonl", inputs.repair),
        ("runs/e1/scores/audit.jsonl", inputs.audit), ("runs/e2/scores/steps.jsonl", inputs.steps),
        ("runs/e2/scores/sessions.jsonl", inputs.sessions), ("data/e3/items.jsonl", inputs.items),
        ("runs/e3/judgments/pointwise.jsonl", inputs.pointwise), ("runs/e3/judgments/known_pairs.jsonl", inputs.known_pairs),
        ("runs/e3/judgments/blv_pairs.jsonl", inputs.blv_pairs), ("runs/e3/generated.jsonl", inputs.generated),
        ("runs/e3/judgments/gen_pairs.jsonl", inputs.gen_pairs), ("runs/*/calls.jsonl", inputs.calls))]))
    if inputs.missing:
        L.append("Missing (treated as not run): " + ", ".join(f"`{m}`" for m in inputs.missing) + "\n")
    if not wrote_paper:
        L.append("**No experiment records exist, so paper/results and paper/figures were not written.**\n")

    sc = study_calls(inputs.calls)
    if not sc.empty:
        L.append("## Call logs (study experiments; pilot excluded)\n")
        g = sc.assign(cost=pd.to_numeric(sc["cost_usd"], errors="coerce").fillna(0.0))
        rows = []
        for (e, m), d in g.groupby(["experiment", "model_key"]):
            st = d["status"].value_counts().to_dict() if "status" in d else {}
            rows.append([e, nm(m), len(d), f"{d['cost'].sum():.2f}", st.get("ok", 0), st.get("refusal", 0),
                         st.get("error", 0)])
        L.append(table(["experiment", "model", "attempts", "USD", "ok", "refusal", "error"], rows))
        L.append(f"Total: {len(g)} attempts, ${g['cost'].sum():.2f}.\n")

    if res["gen"]["models"]:
        L.append("## E1-Gen (C2, C6)\n")
        rows = []
        for m, r in res["gen"]["models"].items():
            n = r["n"]
            rows.append([nm(m), f(r["sgen_nudged"]), f(r["sgen_unguided"]), f(r["gap"]), f(r["overclaim"]),
                         f"{n['nudged']}/{n['unguided']}", n["error"], n["refusal"], n["no_html"], n["not_functional"],
                         n["a_null"], n["overclaim_eligible"], n["selfassess_unparsed"], n["selfassess_retried"],
                         r["vp100_nudged"], r["vp100_unguided"], f(r["clean_nudged"])])
        L.append(table(["model", "S_gen nudged", "S_gen unguided", "default gap", "overclaim", "n nud/ung", "errors",
                        "refusals", "no html", "not functional", "a null", "overclaim n", "self-assess unparsed",
                        "self-assess retried", "violations/100 el. (nudged)", "violations/100 el. (unguided)",
                        "clean rate (nudged)"], rows))
    if res["rep"]["models"]:
        L.append("## E1-Repair (C2)\n")
        rows = [[nm(m), f(r["srep"]), f(r["full_repair"]), f(r["regressions"]), f(r["preserved"]),
                 "; ".join(f"{p}: {f(e)}" for p, e in r["by_provenance"].items()), r["n"]["pages"], r["n"]["error"],
                 r["n"]["no_html"]] for m, r in res["rep"]["models"].items()]
        L.append(table(["model", "S_rep", "full repair", "regressions/page", "preserved", "by provenance", "pages",
                        "errors", "no html"], rows))
        ops = sorted({op for r in res["rep"]["models"].values() for op in r["per_operator"]})
        if ops:
            rows = [[nm(m)] + [f(r["per_operator"].get(op), 2) for op in ops] for m, r in res["rep"]["models"].items()]
            L.append("Resolution rate per operator:\n")
            L.append(table(["model"] + ops, rows))
    if res["aud"]["models"]:
        L.append("## E1-Audit (C1)\n")
        rows = [[nm(m), f(r["saudit"]), f(r["precision"]), f(r["recall"]), f(r["parse_fail"]), r["n"]["faults"],
                 r["n"]["reported"], r["n"]["retried"], r["n"]["error"]] for m, r in res["aud"]["models"].items()]
        L.append(table(["model", "micro-F1", "precision (lower bound)", "recall", "parse-failure rate", "faults",
                        "reported items", "retried", "errors"], rows))

    if res["dcdi"]["models"] or res["drops"]:
        L.append("## E2 (C3, C5, DCDI)\n")
        rows = []
        for m in sorted(set(res["dcdi"]["models"]) | set(res["drops"])):
            r = res["dcdi"]["models"].get(m, {})
            bt = res["beta"].get(m, {})
            dec = res["decomp"]["models"].get(m, {})
            dr = res["drops"].get(m, {})
            beta = (f"{bt['beta']:.3f} [{bt['lo']:.3f}, {bt['hi']:.3f}] (n={bt['n']}, G={bt['groups']})"
                    if bt.get("beta") is not None else f"-- ({bt.get('note', 'no data')})")
            rows.append([nm(m), f(r.get("dcdi")), beta, f(dec.get("len")), f(dec.get("hist")), f(dec.get("tot")),
                         f(r.get("s3")), f(r.get("s5")), dr.get("kept"), dr.get("pairs"),
                         dr.get("session_not_functional"), dr.get("fresh_not_functional"),
                         dr.get("missing_session"), dr.get("missing_fresh"), dr.get("no_applicable_checks"),
                         dr.get("padded_not_functional"), dr.get("missing_padded"),
                         dr.get("padded_length_unmatched")])
        L.append(table(["model", "DCDI", "beta (per doubling)", "DCDI_len", "DCDI_hist", "DCDI_K", "S3", "S5",
                        "kept", "pairs", "drop: session not functional", "drop: fresh not functional",
                        "missing session", "missing fresh", "no applicable checks", "padded not functional",
                        "missing padded", "padded length not matched (excluded)"], rows))
        rows = []
        for m in sorted(set(res["press"]["models"]) | set(res["sess"]["models"])):
            p = res["press"]["models"].get(m, {})
            s = res["sess"]["models"].get(m, {})
            rows.append([nm(m), f(p.get("pressure")), f(p.get("intent_met")), f(s.get("end_regression")),
                         s.get("tool_cycles_mean"), f"{s.get('tool_cycles_min')}-{s.get('tool_cycles_max')}",
                         s.get("sessions"), s.get("context_exhausted"),
                         "; ".join(f"{k}: {v:.2f}" for k, v in sorted(p.get("per_step", {}).items()))])
        L.append(table(["model", "pressure score", "intent met", "end-of-session regression share",
                        "tool cycles/session", "range", "sessions", "context exhausted", "per pressure step"], rows))
        L.append(f"Mean tool-use cycles per session (all models): {res['sess'].get('mean_tool_cycles')}\n")
        if res["toolcalls"]:
            rows = [[nm(m)] + [f"{a.get(arm, {}).get('malformed', '--')}/{a.get(arm, {}).get('tool_calls', '--')}"
                               for arm in ("session", "fresh", "padded")] for m, a in res["toolcalls"].items()]
            L.append("Malformed tool calls / tool calls, by arm:\n")
            L.append(table(["model", "session", "fresh", "padded"], rows))

    e3 = res["e3"]
    if any(e3.get(k) for k in ("e3c", "known", "pointwise", "leakage", "blv_pairs")):
        L.append("## E3 (C4, CMBPE)\n")
        pw = e3.get("pointwise", {})
        for ds in ("blv", "cr"):
            if ds not in pw:
                continue
            rows = [[mth.replace("single:", nm(mth[7:]) + " ") if mth.startswith("single:") else mth,
                     f(v["r"]), f(v["tau"])] for mth, v in pw[ds].items() if isinstance(v, dict) and "r" in v]
            L.append(f"Pointwise vs human overall ({'BLV readers' if ds == 'blv' else 'crowd workers'}; "
                     f"{pw[ds]['n_items']} items; missing scores per judge {pw[ds]['missing_by_judge']}):\n")
            L.append(table(["method", "Pearson r", "Kendall tau-b"], rows))
        if pw.get("crowd_minus_blv"):
            L.append("r(crowd) - r(BLV): " + "; ".join(f"{k}: {f(e)}" for k, e in pw["crowd_minus_blv"].items()) + "\n")
        kn = e3.get("known", {})
        if kn:
            groups = list(kn["accuracy"])
            meths = list(kn["accuracy"]["all"])
            rows = [[m] + [f(kn["accuracy"][g].get(m)) for g in groups] for m in meths]
            L.append(f"Known-answer pairs (E3b; {kn['n_pairs']} pairs; CMBPE {kn['note']}; single-judge verdicts "
                     f"missing in the chosen order {kn['single_missing']}; missing verdicts {kn['missing_by_judge']}):\n")
            L.append(table(["method"] + groups, rows))
            L.append(f"H4b statistic (CMBPE - median single): {f(kn.get('h4b'))}; Krippendorff alpha (E3b): {kn.get('kalpha')}\n")
            L.append("Position consistency on E3b: " + "; ".join(f"{nm(j)}: {f(e)}" for j, e in kn["pc"].items()) + "\n")
        bp = e3.get("blv_pairs", {})
        if bp:
            L.append(f"BLV-preference pairs (E3a; {bp.get('note')}): " + "; ".join(
                f"{k}: {f(e)}" for k, e in bp["accuracy"]["all"].items()) + "\n")
        c = e3.get("e3c", {})
        if c:
            L.append(f"Generator comparison (E3c): {c['n_judgments']} judgments, {c['n_valid']} valid, {c['n_recused']} "
                     f"recused, {c['n_aggregated']} aggregated, {c['n_images']} images; fit converged: {c['converged']}; "
                     f"sd(len) = {c['sd_len']:.1f} chars; Krippendorff alpha {c.get('kalpha')}.\n")
            rows = [[nm(g), f(c["theta"][g]), f(c["s4"][g])] for g in c["cands"]]
            L.append(table(["generator", "theta", "S4 (expected win rate)"], rows))
            rows = [[nm(j), f(c["delta"][j]), f(c["gamma"][j]), f(c["eta"][j]), f(c["pc"].get(j)),
                     f"{c['first_pref_rate'][j]:.3f}", c["missing_by_judge"].get(j)] for j in c["judges"]]
            L.append(table(["judge", "delta (position)", "gamma (length)", "eta (self-pref.)", "PC (E3c)",
                            "first-shown preferred", "missing"], rows))
            L.append(f"Naive panel: PC {c['naive'].get('pc')} (n={c['naive'].get('pc_n')}), gamma {c['naive'].get('gamma')}\n")
        lk = e3.get("leakage", {})
        if lk:
            L.append(f"Leakage classifier (family from anonymised alt text): accuracy {lk.get('accuracy')} "
                     f"[{lk.get('lo')}, {lk.get('hi')}] vs majority {lk.get('majority')} (n={lk.get('n')}, "
                     f"folds={lk.get('folds')}, families {lk.get('families')}).\n")
        if e3.get("transforms"):
            L.append("Anonymisation rules fired: " + "; ".join(f"{nm(g)}: {v['fired']} of {v['n']}"
                                                              for g, v in e3["transforms"].items()) + "\n")

    cp = res["cpds"]
    if cp["summary"]:
        L.append("## CPDS and Pareto (RQ4)\n")
        for fam, summ in cp["summary"].items():
            rows = []
            for m, s in summ.items():
                scen = [k for k, (a, b_, fm) in cpds.SCENARIOS.items() if fm == fam]
                rows.append([nm(m), f"{s['cs']:.3f}", s["c"], s["l"], s["n"], s["n_latency"]] +
                            [cp["cpds"].get(k, {}).get(m) for k in scen] + [cp["pi"].get(fam, {}).get(m)])
            L.append(f"Task family `{fam}` (Pareto set: {', '.join(nm(m) for m in cp['frontier'].get(fam, []))}):\n")
            L.append(table(["model", "CS", "C (USD/task)", "L (median s)", "n", "n latency"] +
                           [f"CPDS {k}" for k, (a, b_, fm) in cpds.SCENARIOS.items() if fm == fam] + ["pi"], rows))
        if cp["sensitivity"]:
            L.append("Rank stability (Kendall tau-b vs default c0=0.01, l0=1): " + "; ".join(
                f"{k}: min {v['min']:.2f}, median {v['median']:.2f}" for k, v in cp["sensitivity"].items()) + "\n")
        if cp["affordability"]:
            L.append(table(["model", "cost to repair 1,000 pages (USD)", "mean page tokens"],
                           [[nm(m), f"{a['cost_1000_pages']:.2f}", a.get("page_tokens")] for m, a in cp["affordability"].items()]))

    if res["dims"]:
        L.append("## Capability profile and CCS (RQ1)\n")
        rows = [[nm(m)] + [f(d[k], 2) for k in ccs.DIMS] + [f(res["ccs"][m]["ccs"], 2), res["ccs"][m]["partial"],
                                                            res["ccs"][m]["arith"]] for m, d in res["dims"].items()]
        L.append(table(["model"] + ccs.DIMS + ["CCS", "CCS partial", "arithmetic mean"], rows))
        rs = res["rank_stability"]
        L.append(f"Kendall tau CCS vs arithmetic mean: {rs['arith']}; leave-one-out: {rs['loo']}\n")
        L.append("Kendall tau between dimension rankings (tau, n models): " +
                 "; ".join(f"{k}: {v}" for k, v in rs["dimension_pairs"].items()) + "\n")

    L.append("## Hypotheses (one-sided, Holm across the family)\n")
    rows = []
    for name, t in res["hyp"]["tests"].items():
        if not t.get("tested"):
            rows.append([name, "not tested", t.get("note", ""), "", "", ""])
            continue
        if isinstance(t.get("stat"), Est):
            stat = f(t["stat"])
        else:
            def r4(v):
                if isinstance(v, float):
                    return f"{v:.4f}"
                if isinstance(v, dict):
                    return "{" + ", ".join(f"{nm(k)}: {r4(x)}" for k, x in v.items()) + "}"
                return nm(v) if isinstance(v, str) and v in M else str(v)
            stat = "; ".join(f"{k}={r4(t[k])}" for k in ("best_open", "pi", "criterion_met", "count_positive",
                                                         "models", "max_eta", "per_judge_p") if k in t)
        rows.append([name, "supported" if t["supported"] else "not supported", stat, f"{t['p']:.4f}",
                     f"{t['p_holm']:.4f}", t.get("description", "")])
    L.append(table(["hypothesis", "result", "statistic", "p", "p (Holm)", "note"], rows))

    if res["decision"]:
        L.append("## Decision matrix (SPEC 9.1, point estimates)\n")
        L.append(table(["context", "choice", "runner-up"],
                       [[k, nm(a) if a != "none" else "none", nm(b_) if b_ != "none" else "none"]
                        for k, (a, b_) in res["decision"].items()]))

    L.append("## Outputs\n")
    L.append(f"values.tex keys written: {len(values)}. Figures: {', '.join(str(p) for p in figs) or 'none'}.\n")
    return "\n".join(L)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", type=pathlib.Path, default=None, help="experiments/ directory")
    ap.add_argument("--paper", type=pathlib.Path, default=None, help="paper/ directory")
    ap.add_argument("--summary", type=pathlib.Path, default=None)
    ap.add_argument("--B", type=int, default=B_DEFAULT)
    ap.add_argument("--seed", type=int, default=SEED)
    args = ap.parse_args(argv)
    paths = Paths(**{k: v for k, v in (("root", args.root), ("paper", args.paper), ("summary", args.summary)) if v})
    inputs = load(paths)
    res = compute(inputs, args.B, args.seed)
    any_records = any((paths.root / f).exists() for f in RECORD_FILES)
    figs, values = [], {}
    if any_records:
        export_latex.write_all(res, inputs, paths.results)
        values = export_latex.values(res, inputs).v
        names = {m: display(inputs.models, m) for m in inputs.models}
        p = figures.drift(res["curves"], names, paths.figures)
        if p:
            figs.append(p)
        p = figures.pareto(res["cpds"]["summary"].get("rep", {}), res["cpds"]["frontier"].get("rep", []), names,
                           {m for m in inputs.models if is_open(inputs.models, m)}, paths.figures)
        if p:
            figs.append(p)
    paths.summary.parent.mkdir(parents=True, exist_ok=True)
    paths.summary.write_text(summary(res, inputs, values, figs, any_records), encoding="utf-8")
    print(f"summary: {paths.summary}")
    if any_records:
        print(f"results: {paths.results} ({len(values)} keys); figures: {[str(p) for p in figs]}")
    else:
        print("no experiment records found: paper outputs not written")
    return 0


if __name__ == "__main__":
    np.seterr(all="ignore")
    sys.exit(main())
