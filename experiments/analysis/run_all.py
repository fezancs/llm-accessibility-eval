"""Run the whole analysis from the logs (CLAUDE.md Phase 4).

    .venv/bin/python -m analysis.run_all                 # from experiments/
    .venv/bin/python -m analysis.run_all --B 200         # quick look (paper numbers use B = 2000)

Writes paper/results/{values.tex, tab_*_body.tex}, paper/figures/fig_*.pdf and
analysis/summary.md. If no E1, E2 or E3 record file exists at all, the paper outputs are
left untouched (the planned-model placeholders stay) and only the summary is written.
"""
